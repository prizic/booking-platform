#!/usr/bin/env node
// Issue #101. Vendor the tested email package into `supabase/functions/_shared/`.
//
// A Supabase Edge Function may only import files under `supabase/functions/`,
// and Deno resolves specifiers literally: `packages/email` imports `./x.js`
// (correct for the Node build, a file that does not exist) and
// `@wlbp/api-contracts` (a bare specifier with no import map). Either one makes
// the function fail to load, and a function that fails to load stops
// `supabase start` from becoming ready — which takes every database gate with
// it.
//
// So the sources are copied and their specifiers rewritten, rather than
// duplicated by hand. The logic still lives in exactly one place; this is a
// generated view of it, and `--check` fails the build if the two drift.
//
// Only the modules an Edge Function actually needs are vendored. `index.ts` is
// not one of them: it exists to give Node consumers a barrel, and it is the
// only file that drags in a type this bundle would otherwise have to invent.
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { pathExists, relativePath, repositoryRoot } from "./workspace.mjs";

const sharedRoot = path.join(repositoryRoot, "supabase/functions/_shared");
const contractsSource = path.join(
  repositoryRoot,
  "packages/api-contracts/src/index.ts",
);

// One entry per package an Edge Function needs. `packages/integrations` is here
// for a second reason: its modules resolve fine locally through a relative path
// that climbs out of `supabase/functions`, but `supabase functions deploy`
// bundles with that directory as its root and refuses to follow one — so the
// Stripe functions would have deployed exactly once, in a shell nobody ran.
//
// `modules` lists only what an Edge Function needs *directly*. Anything they
// import relatively is followed automatically (see `moduleClosure`), so adding
// a helper module to a package cannot leave the vendored copy importing a file
// that was never generated — which fails at `supabase start`, not at build time.
const bundles = [
  {
    directory: "email",
    modules: [
      "brand.ts",
      "delivery.ts",
      "samples.ts",
      "templates.ts",
      "webhook.ts",
      "worker.ts",
    ],
    package: "packages/email",
  },
  {
    directory: "integrations",
    modules: ["stripe.ts"],
    package: "packages/integrations",
  },
  // ADR-0018. The WhatsApp adapter lives in its own directory of the same
  // package, so it gets its own vendored directory and barrel.
  {
    directory: "whatsapp",
    modules: ["classify.ts", "payload.ts", "send.ts", "webhook.ts"],
    package: "packages/integrations",
    source: "src/whatsapp",
  },
];

const banner = (origin) =>
  `// GENERATED by scripts/bundle-edge-shared.mjs from ${origin}.\n` +
  `// Do not edit. Change the package and run \`pnpm bundle:edge\`.\n`;

/**
 * Net `{`/`}` on a line, ignoring braces inside string and comment literals.
 * Enough for a type declaration; not a TypeScript parser.
 */
function braceDelta(line) {
  const withoutLiterals = line
    .replace(/'(?:[^'\\]|\\.)*'/gu, "''")
    .replace(/"(?:[^"\\]|\\.)*"/gu, '""')
    .replace(/\/\/.*$/u, "");
  let delta = 0;
  for (const character of withoutLiterals) {
    if (character === "{") delta += 1;
    else if (character === "}") delta -= 1;
  }
  return delta;
}

/**
 * Pull a named type declaration out of the contracts package. Bringing the
 * whole package across would bring its own bare imports with it, and inventing
 * a local copy of the type would let the two drift silently — so the text of
 * the declaration is taken verbatim, and a rename fails the build here.
 */
export function extractTypeDeclaration(source, name) {
  const lines = source.split("\n");
  const start = lines.findIndex((line) =>
    new RegExp(`^export type ${name}\\b`, "u").test(line),
  );
  if (start === -1) return null;
  // The declaration ends where its braces balance, not at the first line that
  // ends in `;`: a union member line can end in one while the type continues,
  // and stopping there emits a truncated, unparseable copy that only fails when
  // Deno loads the function.
  let depth = 0;
  for (let index = start; index < lines.length; index += 1) {
    depth += braceDelta(lines[index]);
    if (depth === 0 && lines[index].trimEnd().endsWith(";")) {
      return lines.slice(start, index + 1).join("\n");
    }
  }
  return null;
}

/** Every name this module imports from the contracts package. */
export function contractImports(source) {
  const names = new Set();
  const pattern = /import\s+type\s*\{([^}]*)\}\s*from\s*"@wlbp\/api-contracts"/gu;
  for (const match of source.matchAll(pattern)) {
    for (const name of match[1].split(",")) {
      const trimmed = name.replace(/^type\s+/u, "").trim();
      if (trimmed !== "") names.add(trimmed);
    }
  }
  return [...names].sort();
}

/** Node's build specifiers become the literal paths Deno will actually open. */
export function rewriteSpecifiers(source) {
  return source
    .replace(/(from\s*")(\.\/[^"]+)\.js(")/gu, "$1$2.ts$3")
    .replace(/"@wlbp\/api-contracts"/gu, '"./contracts.ts"');
}

/**
 * Every relative module this source imports, as bare file names. Only `./x.js`
 * is followed: a package-internal import is the one form Deno cannot resolve
 * from a vendored copy, and the only form this bundler can fix.
 */
export function relativeImports(source) {
  return [...source.matchAll(/(?:from\s*|import\s*)"\.\/([^"]+)\.js"/gu)].map(
    (match) => `${match[1]}.ts`,
  );
}

/**
 * The entry modules plus everything they import relatively, breadth-first.
 *
 * This is the fix for a demonstrated failure: `intl-locale.ts` was added to
 * `packages/email/src` and imported by three modules, but the bundle listed its
 * modules by hand, so the generated copy imported `./intl-locale.ts` from a file
 * the bundler never wrote. CI caught the drift and would not have caught the
 * consequence — the function fails to load, which stops `supabase start`.
 */
export async function moduleClosure(
  bundle,
  read = (target) => readFile(target, "utf8"),
) {
  const sourceDirectory = bundle.source ?? "src";
  const directory = path.join(repositoryRoot, bundle.package, sourceDirectory);
  const seen = new Set();
  const queue = [...bundle.modules];
  while (queue.length > 0) {
    const moduleName = queue.shift();
    if (seen.has(moduleName)) continue;
    seen.add(moduleName);
    const source = await read(path.join(directory, moduleName));
    for (const imported of relativeImports(source)) {
      if (!seen.has(imported)) queue.push(imported);
    }
  }
  return [...seen];
}

export async function buildBundle(bundle) {
  const contracts = await readFile(contractsSource, "utf8");
  const files = new Map();
  const wanted = new Set();
  const sourceDirectory = bundle.source ?? "src";

  const closure = await moduleClosure(bundle);
  for (const moduleName of closure) {
    const source = await readFile(
      path.join(repositoryRoot, bundle.package, sourceDirectory, moduleName),
      "utf8",
    );
    for (const name of contractImports(source)) wanted.add(name);
    files.set(
      moduleName,
      banner(`${bundle.package}/${sourceDirectory}/${moduleName}`) +
        rewriteSpecifiers(source),
    );
  }

  const declarations = [];
  for (const name of [...wanted].sort()) {
    const declaration = extractTypeDeclaration(contracts, name);
    if (declaration === null) {
      throw new Error(
        `packages/api-contracts no longer exports a type named ${name}; ` +
          `the edge bundle cannot be generated until the import is updated`,
      );
    }
    declarations.push(declaration);
  }
  // Only when something actually needs it. An empty generated file is a file
  // somebody later wonders about.
  if (declarations.length > 0) {
    files.set(
      "contracts.ts",
      banner("packages/api-contracts/src/index.ts") + `${declarations.join("\n\n")}\n`,
    );
  }

  files.set(
    "mod.ts",
    banner(`${bundle.package}/${bundle.source ?? "src"}`) +
      closure.map((moduleName) => `export * from "./${moduleName}";`).join("\n") +
      "\n",
  );
  return files;
}

async function main() {
  const check = process.argv.includes("--check");
  const problems = [];
  const digest = createHash("sha256");
  let count = 0;

  for (const bundle of bundles) {
    const outputDirectory = path.join(sharedRoot, bundle.directory);
    const files = await buildBundle(bundle);
    count += files.size;

    if (check) {
      const existing = (await pathExists(outputDirectory))
        ? await readdir(outputDirectory)
        : [];
      for (const name of existing) {
        if (!files.has(name)) {
          problems.push(`${bundle.directory}/${name} is not generated by the bundler`);
        }
      }
      for (const [name, expected] of files) {
        const target = path.join(outputDirectory, name);
        const actual = (await pathExists(target))
          ? await readFile(target, "utf8")
          : null;
        if (actual !== expected) {
          problems.push(
            `${bundle.directory}/${name} ${actual === null ? "is missing" : "differs from its source"}`,
          );
        }
      }
      continue;
    }

    await rm(outputDirectory, { force: true, recursive: true });
    await mkdir(outputDirectory, { recursive: true });
    for (const [name, contents] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
      await writeFile(path.join(outputDirectory, name), contents, "utf8");
      digest.update(
        `${bundle.directory}/${name}:${createHash("sha256").update(contents).digest("hex")}\n`,
      );
    }
  }

  if (check) {
    if (problems.length > 0) {
      process.exitCode = 1;
      process.stderr.write(
        `the edge shared bundle is stale; run \`pnpm bundle:edge\`:\n- ${problems.join("\n- ")}\n`,
      );
      return;
    }
    process.stdout.write("✓ edge shared bundle matches its packages\n");
    return;
  }

  process.stdout.write(
    `edge shared bundle: ${count} files → ${relativePath(sharedRoot)} (${digest
      .digest("hex")
      .slice(0, 12)})\n`,
  );
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
