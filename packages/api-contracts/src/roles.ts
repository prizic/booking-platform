// Pure rules mirrored from SQL (private.grant_covers / actor_dominates_grants)

const scopeRank: Readonly<Record<GrantScopeV1, number>> = {
  tenant: 3,
  location: 2,
  own: 1,
};

/**
 * Whether one actor grant lets the actor hand out one target grant: same
 * permission, scope at least as wide (tenant > location > own), and a direct
 * grant covers direct or approval while an approval grant covers approval only.
 */
export function grantCovers(actor: RoleGrantV1, target: RoleGrantV1): boolean {
  return (
    actor.permissionKey === target.permissionKey &&
    scopeRank[actor.scope] >= scopeRank[target.scope] &&
    (actor.grantKind === "direct" || target.grantKind === "approval")
  );
}

export interface GrantActorV1 {
  readonly grants: readonly RoleGrantV1[];
  /** `all` for a tenant-mode role; otherwise the actor's assigned locations. */
  readonly locationIds: readonly string[] | "all";
}

export interface GrantTargetV1 {
  readonly grants: readonly RoleGrantV1[];
  /**
   * Locations the target member will hold. `null` is a role-level check (role
   * editor, `assignable`): location containment is then checked at assignment.
   */
  readonly locationIds: readonly string[] | null;
}

function locationsContained(
  actor: GrantActorV1["locationIds"],
  target: GrantTargetV1["locationIds"],
): boolean {
  if (actor === "all" || target === null) return true;
  return target.every((locationId) => actor.includes(locationId));
}

/** Whether the actor may grant this single grant to the target locations. */
export function actorCanGrant(
  actor: GrantActorV1,
  grant: RoleGrantV1,
  targetLocationIds: GrantTargetV1["locationIds"] = null,
): boolean {
  return actor.grants.some(
    (held) =>
      grantCovers(held, grant) &&
      (held.scope === "tenant" ||
        locationsContained(actor.locationIds, targetLocationIds)),
  );
}

/** Target grants the actor cannot hand out; empty means the actor dominates. */
export function uncoveredGrants(
  actor: GrantActorV1,
  target: GrantTargetV1,
): readonly RoleGrantV1[] {
  return target.grants.filter(
    (grant) => !actorCanGrant(actor, grant, target.locationIds),
  );
}

export function dominates(actor: GrantActorV1, target: GrantTargetV1): boolean {
  return uncoveredGrants(actor, target).length === 0;
}

/** Tenant-mode roles carry no location grants; assigned roles no tenant grants. */
export function grantScopeAllowedInMode(
  mode: RoleModeV1,
  scope: GrantScopeV1,
): boolean {
  return mode === "tenant" ? scope !== "location" : scope !== "tenant";
}

export type RoleGrantIssueCodeV1 =
  | "empty"
  | "too_many"
  | "duplicate"
  | "reserved"
  | "unknown_permission"
  | "scope_not_allowed"
  | "grant_kind_not_allowed"
  | "scope_mode_mismatch";

export interface RoleGrantIssueV1 {
  readonly code: RoleGrantIssueCodeV1;
  readonly permissionKey?: string;
}

/**
 * Validates a custom role draft the way `save_role_v1` does (minus dominance,
 * which needs the actor). With a catalog, keys and allowed scope/kind are
 * checked against it too.
 */
export function validateCustomRoleGrantsV1(
  mode: RoleModeV1,
  grants: readonly RoleGrantInputV1[],
  catalog?: readonly PermissionMetaV1[],
): readonly RoleGrantIssueV1[] {
  const issues: RoleGrantIssueV1[] = [];
  if (grants.length === 0) issues.push({ code: "empty" });
  if (grants.length > roleGrantLimitV1) issues.push({ code: "too_many" });
  const seen = new Set<string>();
  for (const grant of grants) {
    const permissionKey = grant.permissionKey;
    if (seen.has(permissionKey)) issues.push({ code: "duplicate", permissionKey });
    seen.add(permissionKey);
    const meta = catalog?.find((item) => item.key === permissionKey);
    if (isReservedPermissionV1(permissionKey) || meta?.reserved === true) {
      issues.push({ code: "reserved", permissionKey });
      continue;
    }
    if (catalog && !meta) {
      issues.push({ code: "unknown_permission", permissionKey });
      continue;
    }
    if (meta && !meta.allowedScopes.includes(grant.scope))
      issues.push({ code: "scope_not_allowed", permissionKey });
    if (meta && !meta.allowedGrantKinds.includes(grant.grantKind))
      issues.push({ code: "grant_kind_not_allowed", permissionKey });
    if (!grantScopeAllowedInMode(mode, grant.scope))
      issues.push({ code: "scope_mode_mismatch", permissionKey });
  }
  return issues;
}

