/**
 * Tenant custom roles (ADR-0019). The database is the authority for every rule
 * here: reserved permissions, built-in locking, scope/mode consistency and
 * dominance (no escalation) are enforced by `save_role_v1`, `archive_role_v1`
 * and `change_staff_access_v1`. The pure functions in this module mirror those
 * rules only so the Dashboard can disable choices the server would refuse.
 */
