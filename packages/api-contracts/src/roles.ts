export interface SaveRoleV1Input {
  readonly tenantId: string;
  readonly requestId: string;
  /** `null` creates a role (optionally duplicated from `sourceRoleId`). */
  readonly roleId: string | null;
  readonly expectedRevision: number | null;
  readonly sourceRoleId: string | null;
  readonly nameEn: string;
  readonly nameAr: string;
  readonly descriptionEn: string | null;
  readonly descriptionAr: string | null;
  readonly mode: RoleModeV1;
  readonly grants: readonly RoleGrantInputV1[];
}

function optionalDescription(value: string | null, what: string): string | null {
  if (value === null) return null;
  const trimmed = value.trim();
  if (trimmed === "") return null;
  return label(trimmed, what, roleDescriptionMaxLengthV1);
}

export function buildSaveRoleV1Request(input: SaveRoleV1Input) {
  const creating = input.roleId === null;
  if (creating !== (input.expectedRevision === null)) fail("role id and revision");
  if (!creating && input.sourceRoleId !== null) fail("source role on update");
  for (const grant of input.grants)
    if (!isKnownCapability(grant.permissionKey)) fail("unknown permission");
  const [issue] = validateCustomRoleGrantsV1(input.mode, input.grants);
  if (issue) fail(`grants (${issue.code})`);
  return {
    p_tenant_id: id(input.tenantId, "tenant"),
    p_request_id: id(input.requestId, "request"),
    p_role_id: input.roleId === null ? null : id(input.roleId, "role id"),
    p_expected_revision:
      input.expectedRevision === null
        ? null
        : count(input.expectedRevision, "expected revision", 1),
    p_source_role_id:
      input.sourceRoleId === null ? null : id(input.sourceRoleId, "source role"),
    p_name_en: label(input.nameEn.trim(), "name_en", roleNameMaxLengthV1),
    p_name_ar: label(input.nameAr.trim(), "name_ar", roleNameMaxLengthV1),
    p_description_en: optionalDescription(input.descriptionEn, "description_en"),
    p_description_ar: optionalDescription(input.descriptionAr, "description_ar"),
    p_location_scope_mode: choice(input.mode, roleModesV1, "role mode"),
    p_grants: input.grants.map((grant) => ({
      permission_key: grant.permissionKey,
      grant_kind: choice(grant.grantKind, grantKindsV1, "grant kind"),
      scope_kind: choice(grant.scope, grantScopesV1, "grant scope"),
    })),
  };
}

export function buildArchiveRoleV1Request(input: {
  readonly tenantId: string;
  readonly requestId: string;
  readonly roleId: string;
  readonly expectedRevision: number;
}) {
  return {
    p_tenant_id: id(input.tenantId, "tenant"),
    p_request_id: id(input.requestId, "request"),
    p_role_id: id(input.roleId, "role id"),
    p_expected_revision: count(input.expectedRevision, "expected revision", 1),
  };
}
