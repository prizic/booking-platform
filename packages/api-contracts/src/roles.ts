// Parsers (snake_case database JSON → camelCase DTOs; exact keys, fail closed)

function fail(what: string): never {
  throw new Error(`Invalid role contract: ${what}`);
}

function object(value: unknown, what: string, keys: readonly string[]) {
  if (typeof value !== "object" || value === null || Array.isArray(value)) fail(what);
  const row = value as Record<string, unknown>;
  const actual = Object.keys(row).sort();
  const expected = [...keys].sort();
  if (
    actual.length !== expected.length ||
    actual.some((key, index) => key !== expected[index])
  )
    fail(`${what} keys`);
  return row;
}

function versioned(value: unknown, what: string, keys: readonly string[]) {
  const row = object(value, what, ["version", ...keys]);
  if (row.version !== 1) fail(`${what} version`);
  return row;
}

const uuidPattern = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/iu;

function id(value: unknown, what: string): string {
  if (typeof value !== "string" || !uuidPattern.test(value)) fail(what);
  return value;
}

function count(value: unknown, what: string, min = 0): number {
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value < min)
    fail(what);
  return value;
}

function bool(value: unknown, what: string): boolean {
  if (typeof value !== "boolean") fail(what);
  return value;
}

function timestamp(value: unknown, what: string): string {
  if (
    typeof value !== "string" ||
    value.length > 64 ||
    !Number.isFinite(Date.parse(value))
  )
    fail(what);
  return value;
}

function nullable<T>(value: unknown, parse: (value: unknown) => T): T | null {
  return value === null ? null : parse(value);
}

function label(value: unknown, what: string, max: number): string {
  if (typeof value !== "string" || value.trim() === "" || value.length > max)
    fail(what);
  return value;
}

function choice<T extends string>(
  value: unknown,
  choices: readonly T[],
  what: string,
): T {
  if (typeof value !== "string" || !(choices as readonly string[]).includes(value))
    fail(what);
  return value as T;
}

function list(value: unknown, what: string, max: number): unknown[] {
  if (!Array.isArray(value) || value.length > max) fail(what);
  return value;
}

function uniqueChoices<T extends string>(
  value: unknown,
  choices: readonly T[],
  what: string,
): readonly T[] {
  const result = list(value, what, choices.length).map((item) =>
    choice(item, choices, what),
  );
  if (result.length === 0 || new Set(result).size !== result.length) fail(what);
  return result;
}

/** `null` when well-formed but unknown to this release (N-1 tolerance). */
function permissionKey(value: unknown): CapabilityName | null {
  if (typeof value !== "string" || !capabilityKeyPattern.test(value))
    fail("permission key");
  return isKnownCapability(value) ? value : null;
}

export function parseRoleCatalogV1(value: unknown): RoleCatalogV1 {
  const row = versioned(value, "catalog", ["tenant_id", "permissions"]);
  const permissions: PermissionMetaV1[] = [];
  for (const item of list(row.permissions, "permissions", 256)) {
    const meta = object(item, "permission", [
      "key",
      "group",
      "allowed_scopes",
      "allowed_grant_kinds",
      "reserved",
      "sort_order",
    ]);
    const key = permissionKey(meta.key);
    if (typeof meta.group !== "string" || !/^[a-z][a-z_]*$/u.test(meta.group))
      fail("permission group");
    const parsed = {
      group: (permissionGroupsV1 as readonly string[]).includes(meta.group)
        ? (meta.group as PermissionGroupV1)
        : "other",
      allowedScopes: uniqueChoices(
        meta.allowed_scopes,
        grantScopesV1,
        "allowed scopes",
      ),
      allowedGrantKinds: uniqueChoices(
        meta.allowed_grant_kinds,
        grantKindsV1,
        "allowed grant kinds",
      ),
      reserved: bool(meta.reserved, "reserved"),
      sortOrder: count(meta.sort_order, "sort order"),
    } as const;
    if (key === null) continue;
    if (permissions.some((existing) => existing.key === key))
      fail("duplicate permission");
    // Conservative union: the local reserved list can only add restrictions.
    permissions.push({
      key,
      ...parsed,
      reserved: parsed.reserved || isReservedPermissionV1(key),
    });
  }
  return { tenantId: id(row.tenant_id, "tenant"), permissions };
}

function parseGrants(value: unknown, mode: RoleModeV1, builtIn: boolean) {
  const grants: RoleGrantV1[] = [];
  let hasUnknownGrants = false;
  for (const item of list(value, "grants", 256)) {
    const grant = object(item, "grant", ["permission_key", "grant_kind", "scope_kind"]);
    const key = permissionKey(grant.permission_key);
    const grantKind = choice(grant.grant_kind, grantKindsV1, "grant kind");
    const scope = choice(grant.scope_kind, grantScopesV1, "grant scope");
    if (!grantScopeAllowedInMode(mode, scope)) fail("grant scope for mode");
    if (key === null) {
      hasUnknownGrants = true;
      continue;
    }
    if (!builtIn && isReservedPermissionV1(key)) fail("reserved grant on custom role");
    if (grants.some((existing) => existing.permissionKey === key))
      fail("duplicate grant");
    grants.push({ permissionKey: key, grantKind, scope });
  }
  return { grants, hasUnknownGrants };
}

function parseRole(value: unknown): RoleV1 {
  const row = object(value, "role", [
    "id",
    "key",
    "is_builtin",
    "name_en",
    "name_ar",
    "description_en",
    "description_ar",
    "location_scope_mode",
    "revision",
    "archived",
    "archived_at",
    "updated_at",
    "duplicated_from_role_id",
    "administrator",
    "active_members",
    "pending_invitations",
    "assignable",
    "grants",
  ]);
  const isBuiltIn = bool(row.is_builtin, "is_builtin");
  const mode = choice(row.location_scope_mode, roleModesV1, "role mode");
  const base = {
    id: id(row.id, "role id"),
    mode,
    revision: count(row.revision, "role revision", 1),
    archived: bool(row.archived, "archived"),
    archivedAt: nullable(row.archived_at, (v) => timestamp(v, "archived_at")),
    updatedAt: timestamp(row.updated_at, "updated_at"),
    duplicatedFromRoleId: nullable(row.duplicated_from_role_id, (v) =>
      id(v, "duplicated_from_role_id"),
    ),
    administrator: bool(row.administrator, "administrator"),
    activeMembers: count(row.active_members, "active members"),
    pendingInvitations: count(row.pending_invitations, "pending invitations"),
    assignable: bool(row.assignable, "assignable"),
    ...parseGrants(row.grants, mode, isBuiltIn),
  };
  if (isBuiltIn) {
    const key = choice(row.key, builtInRoleKeys, "built-in role key");
    if (
      row.name_en !== null ||
      row.name_ar !== null ||
      row.description_en !== null ||
      row.description_ar !== null ||
      row.archived_at !== null ||
      row.duplicated_from_role_id !== null
    )
      fail("built-in role carries custom fields");
    if (row.archived !== false) fail("built-in role archived");
    return { kind: "builtin", key, ...base };
  }
  if (typeof row.key !== "string" || !customRoleKeyPattern.test(row.key))
    fail("custom role key");
  if (row.archived !== (row.archived_at !== null)) fail("archive state");
  return {
    kind: "custom",
    key: row.key,
    nameEn: label(row.name_en, "name_en", roleNameMaxLengthV1),
    nameAr: label(row.name_ar, "name_ar", roleNameMaxLengthV1),
    descriptionEn: nullable(row.description_en, (v) =>
      label(v, "description_en", roleDescriptionMaxLengthV1),
    ),
    descriptionAr: nullable(row.description_ar, (v) =>
      label(v, "description_ar", roleDescriptionMaxLengthV1),
    ),
    ...base,
  };
}

export function parseRolesV1(value: unknown): RolesV1 {
  const row = versioned(value, "roles", ["tenant_id", "can_manage_roles", "roles"]);
  const roles = list(row.roles, "roles", 1000).map(parseRole);
  if (new Set(roles.map((role) => role.id)).size !== roles.length)
    fail("duplicate role");
  return {
    tenantId: id(row.tenant_id, "tenant"),
    canManageRoles: bool(row.can_manage_roles, "can_manage_roles"),
    roles,
  };
}

