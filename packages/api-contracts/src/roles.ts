/**
 * Maps a PostgREST error from a role RPC to a known code. The message must be
 * exactly the code; `role_in_use` / `role_scope_in_use` may carry
 * `{"members":n,"invitations":n}` as the error detail.
 */
export function parseRoleMutationErrorV1(error: unknown): RoleMutationErrorV1 | null {
  if (typeof error !== "object" || error === null) return null;
  const { message, details } = error as { message?: unknown; details?: unknown };
  if (typeof message !== "string") return null;
  const code = (roleMutationErrorCodesV1 as readonly string[]).find(
    (candidate) => candidate === message.trim(),
  ) as RoleMutationErrorCodeV1 | undefined;
  if (!code) return null;
  if (
    (code === "role_in_use" || code === "role_scope_in_use") &&
    typeof details === "string"
  ) {
    try {
      const parsed: unknown = JSON.parse(details);
      if (typeof parsed === "object" && parsed !== null) {
        const { members, invitations } = parsed as Record<string, unknown>;
        if (
          typeof members === "number" &&
          Number.isSafeInteger(members) &&
          members >= 0 &&
          typeof invitations === "number" &&
          Number.isSafeInteger(invitations) &&
          invitations >= 0
        )
          return { code, members, invitations };
      }
    } catch {
      // Detail is advisory; the code alone is still meaningful.
    }
  }
  return { code };
}

